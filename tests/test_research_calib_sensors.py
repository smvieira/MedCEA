MAP = {"sht45": "sht45_1", "scd30": "scd30_1"}
_CACHE = {}


def fitted(key, **kw):
    """(header, rows, fit result) of one synthetic dataset, cached per key."""
    if key not in _CACHE:
        fit_kw = kw.pop("fit_kw", {})
        rows = S.make_rows(**kw)
        h = S.header_for(rows)
        _CACHE[key] = (h, rows, sensor_fit.fit(h, rows, MAP, **fit_kw))
    return _CACHE[key]


def numbers(obj):
    if isinstance(obj, bool) or obj is None or isinstance(obj, str):
        return
    if isinstance(obj, (int, float)):
        yield obj
    elif isinstance(obj, dict):
        for v in obj.values():
            yield from numbers(v)
    elif isinstance(obj, list):
        for v in obj:
            yield from numbers(v)


class RoundTrip(unittest.TestCase):
    """The live data's shape: 3 h, one 10-minute outage, CO2 with momentum."""

    @classmethod
    def setUpClass(cls):
        cls.h, cls.rows, cls.r = fitted("base", hours=3.0, outages=[(5000, 5600)])
        cls.s = cls.r["sensors"]

    def test_publish_interval(self):
        for m in ("sht45", "scd30"):
            e = self.s[m]["publish_interval_s"]
            self.assertTrue(e["applied"], e)
            self.assertEqual(e["source"], "fitted")
            self.assertAlmostEqual(e["value"], 2.988, delta=0.01)
            self.assertLessEqual(e["ci95"][0], e["value"])
            self.assertGreaterEqual(e["ci95"][1], e["value"])

    def test_start_offset_is_chosen_zero(self):
        for m in ("sht45", "scd30"):
            self.assertEqual(self.s[m]["start_offset_s"]["value"], 0.0)
            self.assertEqual(self.s[m]["start_offset_s"]["source"], "chosen")

    def test_latency_is_confounded(self):
        # the generator's ingest delay on top of the latency: sht45 +0/+0.1 s, scd30 +0.25..+0.45 s
        for m, want in (("sht45", 0.8 + 0.05), ("scd30", 1.2 + 0.35)):
            e = self.s[m]["latency_s"]
            self.assertEqual(e["source"], "fitted_confounded")
            self.assertIn("clock", e["note"])
            self.assertAlmostEqual(e["value"], want, delta=0.12, msg=m)
            self.assertLessEqual(e["p5"], e["p50"])
            self.assertLessEqual(e["p50"], e["p95"])

    def test_quantisation(self):
        for m in ("sht45", "scd30"):
            for tag, e in self.s[m]["quantisation"].items():
                self.assertEqual(e["value"], 0.01, (m, tag))

    def test_noise_structure_function_intercept(self):
        for m, tag, want in (("sht45", "air_temperature", 0.012), ("sht45", "air_humidity", 0.016),
                             ("scd30", "air_temperature", 0.012), ("scd30", "air_humidity", 0.02)):
            e = self.s[m]["noise_sd"][tag]
            self.assertTrue(e["applied"], (m, tag, e))
            self.assertAlmostEqual(e["value"], want, delta=0.15 * want, msg=(m, tag))
            self.assertLess(e["d1_autocorrelation"], 0)
            self.assertEqual(len(e["v_k"]), 4)
            self.assertLessEqual(e["relative_residual"], sensor_fit.REL_RESID_MAX)

    def test_co2_noise_refused_as_filtered(self):
        e = self.s["scd30"]["noise_sd"]["co2"]
        self.assertFalse(e["applied"])
        self.assertEqual(e["source"], "not_identifiable")
        self.assertIn("not separable from filtered process variation", e["why"])
        self.assertGreater(e["d1_autocorrelation"], 0)
        self.assertNotIn("value", e)
        rel = self.s["scd30"]["noise_rel_sd"]["co2"]
        self.assertFalse(rel["applied"])

    def test_relative_offsets(self):
        b = self.s["scd30"]["bias"]
        self.assertAlmostEqual(b["air_temperature"]["value"], 2.04, delta=0.02)
        self.assertAlmostEqual(b["air_humidity"]["value"], -7.03, delta=0.02)
        self.assertEqual(b["air_temperature"]["relative_to"], "sht45")
        self.assertEqual(b["co2"]["value"], 0.0)
        self.assertEqual(b["co2"]["source"], "not_identifiable")
        for tag in ("air_temperature", "air_humidity"):
            self.assertEqual(self.s["sht45"]["bias"][tag], dict(self.s["sht45"]["bias"][tag], value=0.0,
                                                                 source="chosen"))

    def test_constant_offset_is_the_default_model(self):
        sh = self.s["scd30"]["self_heating_c"]
        self.assertFalse(sh["applied"])
        self.assertAlmostEqual(sh["value"], 2.04, delta=0.02)
        self.assertEqual(self.s["scd30"]["humidity_model"], dict(self.s["scd30"]["humidity_model"],
                                                                 value="constant_offset", source="chosen"))
        rel = self.r["relative"]["scd30"]
        self.assertAlmostEqual(rel["slope_dRH_vs_RH"]["observed"], 0.0, delta=0.03)
        self.assertLess(rel["slope_dRH_vs_RH"]["self_heating"], -0.05)
        self.assertEqual(set(rel["predicted_offset_at_rh"]["self_heating"]), {"50", "70", "85", "95"})

    def test_validity_is_the_reference_range(self):
        lo, hi = self.r["validity"]["air_humidity"]
        rh = [int(round(float(r["value"]) * 100)) / 100.0 for r in self.rows
              if r["sensor"] == "sht45_1" and r["tag"] == "air_humidity"]
        self.assertEqual((lo, hi), (min(rh), max(rh)))

    def test_bias_sd_datasheet(self):
        self.assertEqual(self.s["sht45"]["bias_sd"]["air_temperature"]["value"], 0.05)
        self.assertEqual(self.s["sht45"]["bias_sd"]["air_humidity"]["value"], 0.5)
        e = self.s["scd30"]["bias_sd"]["co2"]
        self.assertEqual(e["source"], "datasheet")
        self.assertAlmostEqual(e["value"], (30 + 0.03 * e["at_ppm"]) / 2, places=3)
        self.assertNotIn("air_temperature", self.s["scd30"]["bias_sd"])
        self.assertTrue(any(u["what"] == "correlated absolute error" for u in self.r["unmodelled"]))

    def test_outage_segments_and_no_dropout(self):
        self.assertEqual(len(self.r["segments"]), 2)
        gaps = [o for o in self.r["outages"] if o["why"] == "gap in the data"]
        self.assertEqual(len(gaps), 1)
        self.assertAlmostEqual(gaps[0]["seconds"], 600, delta=4)
        for m in ("sht45", "scd30"):
            self.assertEqual(self.s[m]["dropout_p"]["value"], 0.0)
            self.assertEqual(self.s[m]["dropout_p"]["misses"], 0)
        self.assertEqual(self.r["cadence"]["nominal_s"], 3.0)
        self.assertEqual(self.r["refused_sensors"], [])

    def test_six_significant_digits_and_finite(self):
        for v in numbers(self.r["sensors"]):
            self.assertTrue(math.isfinite(v))
            if isinstance(v, float):
                self.assertEqual(v, float("%.6g" % v))
        for u in self.r["unmodelled"]:
            for v in numbers(u):
                self.assertTrue(math.isfinite(v))

    def test_jitter_and_skipped_cycles_unmodelled(self):
        whats = {(u["what"], u["sensor"]) for u in self.r["unmodelled"]}
        self.assertIn(("publish jitter", "sht45"), whats)
        self.assertIn(("skipped cycles", "scd30"), whats)
        self.assertIn(("fast process variation not in the model", "sht45"), whats)


class Lattice(unittest.TestCase):
    """A coarser lattice (0.05 C), a stronger AR(1) process, dropouts, white CO2 noise."""

    @classmethod
    def setUpClass(cls):
        cls.h, cls.rows, cls.r = fitted(
            "lattice", hours=3.0, co2_momentum=False, process_sd={"air_temperature": 0.3},
            sht45={"quantisation": {"air_temperature": 0.05, "air_humidity": 0.01},
                   "noise_sd": {"air_temperature": 0.05, "air_humidity": 0.016}, "dropout_p": 0.02})
        cls.s = cls.r["sensors"]

    def test_lattice_step(self):
        self.assertEqual(self.s["sht45"]["quantisation"]["air_temperature"]["value"], 0.05)
        self.assertEqual(self.s["sht45"]["quantisation"]["air_humidity"]["value"], 0.01)

    def test_noise_on_the_lattice_under_a_process(self):
        e = self.s["sht45"]["noise_sd"]["air_temperature"]
        self.assertTrue(e["applied"], e)
        self.assertAlmostEqual(e["value"], 0.05, delta=0.0075)
        procs = [u for u in self.r["unmodelled"] if u["what"].startswith("fast process") and u["sensor"] == "sht45"
                 and u["tag"] == "air_temperature"]
        self.assertEqual(len(procs), 1)
        self.assertGreater(procs[0]["variance_per_cycle"], 0)

    def test_dropout(self):
        e = self.s["sht45"]["dropout_p"]
        self.assertTrue(e["applied"], e)
        self.assertAlmostEqual(e["value"], 0.02, delta=0.006)
        self.assertLessEqual(e["ci95"][0], 0.02)
        self.assertGreaterEqual(e["ci95"][1], 0.02 * 0.95)

    def test_white_co2_noise_fitted_and_homoscedastic(self):
        e = self.s["scd30"]["noise_sd"]["co2"]
        self.assertTrue(e["applied"], e)
        self.assertAlmostEqual(e["value"], 4.0, delta=0.6)
        rel = self.s["scd30"]["noise_rel_sd"]["co2"]
        self.assertEqual((rel["value"], rel["source"], rel["applied"]), (0.0, "not_identifiable", True))
        self.assertIn("heteroscedasticity", rel["why"])


class SelfHeating(unittest.TestCase):
    """An SCD30 that self-heats by 2.04 C, with a small residual humidity offset."""

    @classmethod
    def setUpClass(cls):
        cls.h, cls.rows, cls.r = fitted(
            "selfheat", hours=3.0, process_sd={"air_humidity": 3.0},
            scd30={"bias": {}, "self_heating_c": 2.04, "noise_sd": {"co2": 4.0, "air_temperature": 0.012,
                                                                     "air_humidity": 0.02}},
            fit_kw={"humidity_model": "self_heating"})
        cls.s = cls.r["sensors"]["scd30"]

    def test_self_heating_model(self):
        self.assertTrue(self.s["self_heating_c"]["applied"])
        self.assertAlmostEqual(self.s["self_heating_c"]["value"], 2.04, delta=0.02)
        self.assertEqual(self.s["bias"]["air_temperature"]["value"], 0.0)
        self.assertEqual(self.s["bias"]["air_temperature"]["source"], "chosen")
        self.assertAlmostEqual(self.s["bias"]["air_humidity"]["value"], 0.0, delta=0.05)
        rel = self.r["relative"]["scd30"]
        self.assertAlmostEqual(rel["residual_median"]["self_heating"], 0.0, delta=0.05)
        self.assertAlmostEqual(rel["slope_dRH_vs_RH"]["observed"], rel["slope_dRH_vs_RH"]["self_heating"],
                               delta=0.01)
        self.assertEqual(rel["humidity_model"], "self_heating")

    def test_the_humidity_offset_follows_the_physics(self):
        """RH_scd = RH_sht * rho_sat(T) / rho_sat(T + 2.04): the fitted dRH at the median RH."""
        from research.twin_plant.chamber import saturation_density
        rel = self.r["relative"]["scd30"]
        t = rel["predicted_offset_at_rh"]["temperature"]
        k = saturation_density(t) / saturation_density(t + 2.04)
        self.assertAlmostEqual(rel["predicted_offset_at_rh"]["self_heating"]["70"], 70 * (k - 1), delta=0.1)


class Refusals(unittest.TestCase):
    def test_too_little_data_refuses_every_fitted_field(self):
        rows = S.make_rows(hours=0.5)
        r = sensor_fit.fit(S.header_for(rows), rows, MAP)
        self.assertEqual(sorted(r["refused_sensors"]), ["scd30", "sht45"])
        for m in ("sht45", "scd30"):
            self.assertEqual(r["sensors"][m]["publish_interval_s"]["source"], "not_enough_data")
            self.assertIn("no segment of 3600 s", r["sensors"][m]["publish_interval_s"]["why"])
            self.assertEqual(r["sensors"][m]["noise_sd"]["air_temperature"]["source"], "not_enough_data")
        self.assertEqual(r["validity"], {})

    def test_wrong_clock_or_time_zone(self):
        base = S.make_rows(hours=1.5)
        for shift, word in ((-3600, "time zone"), (10, "time zone")):
            rows = copy.deepcopy(base)
            for row in rows:
                row["measured_at"] = segments.format_us(segments.parse_us(row["measured_at"]) + shift * 1000000)
            rows.sort(key=dataset._key)
            r = sensor_fit.fit(S.header_for(rows), rows, MAP)
            e = r["sensors"]["sht45"]["latency_s"]
            self.assertFalse(e["applied"])
            self.assertIn(word, e["why"])
            self.assertNotIn("value", e)

    def test_noise_not_separable_from_the_lattice(self):
        rows = S.make_rows(hours=1.5, process_sd={"air_temperature": 0.02},
                           sht45={"noise_sd": {"air_temperature": 0.0, "air_humidity": 0.016}})
        r = sensor_fit.fit(S.header_for(rows), rows, MAP)
        e = r["sensors"]["sht45"]["noise_sd"]["air_temperature"]
        self.assertFalse(e["applied"], e)
        self.assertNotIn("value", e)

    def test_poor_structure_function(self):
        saved = sensor_fit.REL_RESID_MAX
        sensor_fit.REL_RESID_MAX = -1.0
        self.addCleanup(setattr, sensor_fit, "REL_RESID_MAX", saved)
        h, rows, _ = fitted("base", hours=3.0, outages=[(5000, 5600)])
        r = sensor_fit.fit(h, rows, MAP)
        self.assertIn("not a straight line", r["sensors"]["sht45"]["noise_sd"]["air_temperature"]["why"])

    def test_irregular_schedule(self):
        saved = sensor_fit.CV_MAX
        sensor_fit.CV_MAX = 0.0
        self.addCleanup(setattr, sensor_fit, "CV_MAX", saved)
        h, rows, _ = fitted("base", hours=3.0, outages=[(5000, 5600)])
        r = sensor_fit.fit(h, rows, MAP)
        self.assertIn("no regular schedule", r["sensors"]["sht45"]["publish_interval_s"]["why"])

    def test_too_few_pairs(self):
        saved = sensor_fit.MIN_PAIRS
        sensor_fit.MIN_PAIRS = 10 ** 6
        self.addCleanup(setattr, sensor_fit, "MIN_PAIRS", saved)
        h, rows, _ = fitted("base", hours=3.0, outages=[(5000, 5600)])
        r = sensor_fit.fit(h, rows, MAP)
        self.assertEqual(r["sensors"]["scd30"]["bias"]["air_temperature"]["source"], "not_enough_data")
        self.assertFalse(r["sensors"]["scd30"]["self_heating_c"]["applied"])
        self.assertEqual(r["relative"], {})

    def test_weak_estimate_not_applied(self):
        rows = S.make_rows(hours=1.5, sht45={"dropout_p": 0.0004})
        r = sensor_fit.fit(S.header_for(rows), rows, MAP)
        e = r["sensors"]["sht45"]["dropout_p"]
        if e["misses"] == 0:
            self.skipTest("no dropout drawn")
        self.assertTrue(e["weak"])
        self.assertFalse(e["applied"])
        self.assertIn("default stays", e["why"])

    def test_more_than_two_decimals(self):
        with self.assertRaises(segments.DataError):
            segments.hundredths("21.005")
        self.assertEqual(segments.hundredths("21.5"), 2150)
        self.assertEqual(segments.hundredths("-3"), -300)
        for bad in ("NaN", "x", None, "Infinity"):
            with self.assertRaises(segments.DataError):
                segments.hundredths(bad)

    def test_bad_map(self):
        h, rows, _ = fitted("base", hours=3.0, outages=[(5000, 5600)])
        for m, ref, why in (({"sht45": "nope_1"}, "sht45", "no sensor nope_1"),
                            ({"bme280": "sht45_1"}, "bme280", "not a model sensor"),
                            ({"scd30": "scd30_1"}, "sht45", "not in --map"),
                            ({"sht45": "scd30_1"}, "sht45", "does not")):
            with self.assertRaisesRegex(sensor_fit.FitError, why):
                sensor_fit.fit(h, rows, m, reference=ref)
        self.assertEqual(sensor_fit.parse_map("sht45=sht45_1, scd30=scd30_1"), MAP)
        for bad in ("", "sht45", "a=b=c", "a=1,a=2"):
            with self.assertRaises(sensor_fit.FitError):
                sensor_fit.parse_map(bad)


class Segments(unittest.TestCase):
    def test_cadence_classes(self):
        t = [0.0]
        for d in [3.0] * 50 + [12.0] + [3.0] * 50 + [45.0] + [3.0] * 30 + [75.0] + [3.0] * 30:
            t.append(t[-1] + d)
        c = segments.cadence(t)
        self.assertEqual(c["nominal"], 3.0)
        self.assertEqual([d for _, d in c["skipped"]], [12.0, 45.0])
        self.assertEqual([d for _, d in c["outages"]], [75.0])
        self.assertEqual(len(c["segments"]), 2)
        self.assertEqual(sum(h["n"] for h in c["skipped_hist"]), 2)

    def test_end_of_data_outage(self):
        rows = S.make_rows(hours=1.2)
        b = segments.Board(rows, ["sht45_1", "scd30_1"])
        cut = segments.format_us(segments.parse_us(rows[-1]["ingested_at"]) + 3600 * 1000000)
        recs = segments.outage_records(b, cut)
        self.assertEqual(recs[-1]["why"], "end of the data before the snapshot's cut")
        self.assertEqual(segments.outage_records(b, rows[-1]["ingested_at"]), [])

    def test_a_cycle_is_one_measured_at(self):
        rows = S.make_rows(hours=0.1)
        dup = dict(rows[0])
        with self.assertRaisesRegex(segments.DataError, "twice"):
            segments.Board(rows + [dup], ["sht45_1", "scd30_1"])


class Determinism(unittest.TestCase):
    def test_same_dataset_same_result(self):
        h, rows, r1 = fitted("base", hours=3.0, outages=[(5000, 5600)])
        r2 = sensor_fit.fit(h, rows, MAP)
        self.assertEqual(json.dumps(r1, sort_keys=True), json.dumps(r2, sort_keys=True))

    def test_bootstrap_draws(self):
        rng = stats.rng_for("x" * 64, "f")
        rng2 = stats.rng_for("x" * 64, "f")
        self.assertEqual(stats.resample_blocks(7, rng), [int(rng2.random() * 7) for _ in range(7)])
        self.assertNotEqual(stats.rng_for("x" * 64, "g").random(), stats.rng_for("x" * 64, "f").random())

    def test_sig6(self):
        self.assertEqual(stats.sig6(2.98698123), 2.98698)
        self.assertEqual(stats.sig6(0.0), 0.0)
        self.assertEqual(stats.sig6(-7.03), -7.03)
        self.assertEqual(stats.sig6(123456789), 123457000.0)
        for bad in (float("nan"), float("inf"), True, "1"):
            with self.assertRaises(ValueError):
                stats.sig6(bad)

    def test_structure_function_line(self):
        vk = {k: (1000, 2e-4 + 3e-5 * k) for k in sensor_fit.LAGS}
        a, c = sensor_fit._structure(vk)
        self.assertAlmostEqual(a, 2e-4, places=12)
        self.assertAlmostEqual(c, 3e-5, places=12)

    def test_wilson_and_tails(self):
        self.assertEqual(stats.wilson(0, 100)[0], 0.0)
        lo, hi = stats.wilson(10, 100)
        self.assertLess(lo, 0.1)
        self.assertGreater(hi, 0.1)
        self.assertAlmostEqual(stats.chi2_sf(16.919, 9), 0.05, places=3)
        self.assertAlmostEqual(stats.chi2_sf(2.0, 2), math.exp(-1), places=9)
        self.assertAlmostEqual(stats.p_zero_difference(1e-9, 0.01), 1.0, places=6)
        self.assertLess(stats.p_zero_difference(1.0, 0.01), 0.01)
        mc = random.Random(1)
        n, z = 200000, 0
        for _ in range(n):
            a, b = mc.gauss(0, 0.01), mc.gauss(0, 0.01)
            ph = mc.random()
            z += round(a / 0.01 + ph) == round(b / 0.01 + ph)
        self.assertAlmostEqual(z / n, stats.p_zero_difference(0.01 * math.sqrt(2), 0.01), delta=0.01)


class Cli(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp = tempfile.mkdtemp(prefix="rs-calib-")
        cls.ds = S.write_dataset(os.path.join(cls.tmp, "ds"), S.make_rows(hours=1.5))
        cls.short = S.write_dataset(os.path.join(cls.tmp, "short"), S.make_rows(hours=0.5))

    @classmethod
    def tearDownClass(cls):
        shutil.rmtree(cls.tmp)

    def calib(self, *args):
        return subprocess.run([sys.executable, "-m", "research.calib", *args], cwd=REPO, capture_output=True,
                              text=True, timeout=300)

    def test_fit_is_byte_identical_and_verifies(self):
        outs = []
        for name in ("a", "b"):
            out = os.path.join(self.tmp, "cal-%s.yaml" % name)
            p = self.calib("fit-sensors", self.ds, "--map", "sht45=sht45_1,scd30=scd30_1", "--name", "unit01-s1",
                           "--out", out, "--report", out + ".txt", "--allow-dirty")
            self.assertEqual(p.returncode, 0, p.stderr)
            self.assertIn("written, sha256", p.stdout)
            with open(out, "rb") as f:
                outs.append(f.read())
            self.assertTrue(os.path.exists(out + ".txt"))
        self.assertEqual(outs[0], outs[1])
        p = self.calib("verify", os.path.join(self.tmp, "cal-a.yaml"))
        self.assertEqual(p.returncode, 0, p.stderr)
        self.assertIn("every one the model's default", p.stdout)
        p = self.calib("fit-sensors", self.ds, "--map", "sht45=sht45_1,scd30=scd30_1", "--name", "unit01-s1",
                       "--out", os.path.join(self.tmp, "cal-a.yaml"), "--allow-dirty")
        self.assertEqual(p.returncode, 2)
        self.assertIn("already exists", p.stderr)

    def test_not_enough_data_exits_3_and_writes_nothing(self):
        out = os.path.join(self.tmp, "never.yaml")
        p = self.calib("fit-sensors", self.short, "--map", "sht45=sht45_1,scd30=scd30_1", "--name", "x",
                       "--out", out, "--report", out + ".txt", "--allow-dirty")
