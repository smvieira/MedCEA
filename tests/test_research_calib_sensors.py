#!/usr/bin/env python3
"""The sensor fit of research Phase 3 (research/calib/{segments,stats,sensor_fit}.py), offline.

Round trips: synthetic datasets shaped like snapshot 1's live series (tests/_rs_synth.py:
one board cycle every ~3 s, measured_at whole seconds shared by every tag of the cycle,
the SCD30 +2.04 C / -7.03 %RH against the SHT45), generated by twin_plant.sensors
.SensorBank with known values, are fitted, and the fit must give those values back:
publish interval, start offset (0, chosen), latency, quantisation (also a coarser lattice),
noise (the structure function's intercept, under an AR(1) process term), the relative
offsets, the self-heating model, dropout, the datasheet bias_sd. Outages are segmented and
never counted as dropouts. The refusals: too little data (also exit 3 from the CLI, nothing
written), a wrong clock or time zone, filtered noise (CO2), noise not separable from the
lattice, a poor structure function, an irregular schedule, too few pairs, a weak interval.
Determinism: the same dataset gives the same result and the same file (6 significant
digits, a bootstrap whose only random call is int(rng.random() * n) from a seeded Random).

Run:  python3 -m unittest tests.test_research_calib_sensors
"""
