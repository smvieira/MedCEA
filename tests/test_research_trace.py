"""apps/research/db/agent_trace.sql (research Phase 4a, stage 2): the agent trace.

  AsText      the SQL as text: every table append-only (ENABLE ALWAYS), every function
              SECURITY DEFINER with a pinned search_path and no PUBLIC, the per-port
              allow-lists, the size limits, rs_session's grants and the assert block
  Wiring      the deploy runs it after lake_api.sql and before the passwords; the
              password variable is generated by configure.sh and listed in config.env.example
  RealPostgres  on a throwaway PostgreSQL when initdb/pg_ctl/psql are found (PATH, or
              MEDCEA_TEST_PG_BIN; MEDCEA_TEST_PG_SHARE for initdb -L), else skipped
"""
