LAKE_API = os.path.join(APP, "db", "lake_api.sql")
GRANTS = os.path.join(APP, "db", "grants.sql")
ASSERT = os.path.join(APP, "db", "assert_grants.sql")
TABLES = ["session", "revocation", "claim_use", "blob", "blob_ref", "state", "event"]
GRANTED = ["open_session", "append_event", "put_blob", "checkpoint", "use_claim", "revoke", "session_status", "events"]


def read(p):
    with open(p) as f:
        return f.read()


def code(text):
    return "\n".join(l.split("--", 1)[0] for l in text.splitlines())


class AsText(unittest.TestCase):
    def setUp(self):
        self.sql = code(read(TRACE))

    def test_every_table_is_append_only_always(self):
        for t in TABLES:
            self.assertIn("'agent_trace.%s'" % t, self.sql)
            self.assertIn("CREATE TABLE IF NOT EXISTS agent_trace.%s " % t, self.sql)
        self.assertIn("ENABLE ALWAYS TRIGGER append_only_row", self.sql)
        self.assertIn("ENABLE ALWAYS TRIGGER append_only_truncate", self.sql)
        self.assertIn("BEFORE UPDATE OR DELETE", self.sql)
        self.assertIn("BEFORE TRUNCATE", self.sql)

    def test_every_function_is_definer_pinned_and_closed(self):
        fns = re.findall(r"CREATE OR REPLACE FUNCTION (agent_trace\.\w+)\((.*?)\n(?:\$\$;|REVOKE)", self.sql, re.S)
        names = re.findall(r"CREATE OR REPLACE FUNCTION (agent_trace\.\w+)\(", self.sql)
        self.assertGreaterEqual(len(names), 17)
        for n in names:
            m = re.search(r"CREATE OR REPLACE FUNCTION %s\(.*?\$\$" % re.escape(n), self.sql, re.S)
            self.assertIsNotNone(m, n)
            head = m.group(0)
            self.assertIn("SECURITY DEFINER", head, n)
            self.assertIn("SET search_path = pg_catalog, pg_temp", head, n)
            self.assertRegex(self.sql, r"REVOKE ALL ON FUNCTION %s\(" % re.escape(n))
        self.assertNotRegex(self.sql, r"\bGRANT\b")          # grants are grants.sql's
        self.assertNotIn("PASSWORD", self.sql)               # the deploy sets it

    def test_port_allow_lists(self):
        m = re.search(r"_port_events.*?\$\$(.*?)\$\$", self.sql, re.S).group(1)
        lists = dict((k, re.findall(r"'(\w+)'", v)) for k, v in
                     re.findall(r"WHEN '(\w+)'\s+THEN ARRAY\[(.*?)\]", m, re.S))
        self.assertEqual(set(lists), {"person", "agent", "server"})
        for ev in ("gate_decided", "proposal_decided", "session_minted", "claim_exchanged", "claim_reused",
                   "session_revoked"):
            self.assertIn(ev, lists["person"])
            self.assertNotIn(ev, lists["agent"] + lists["server"])      # R8: research-session only
        self.assertEqual(set(lists["agent"]), {"turn_request", "turn_response", "tool_call", "tool_result",
                                               "checkpoint", "proposal", "stop"})
        self.assertNotIn("sim_finished", lists["agent"])
        self.assertIn("sim_finished", lists["server"])
        self.assertIn("replay_result", lists["server"])

    def test_limits_and_binding(self):
        self.assertIn("16384", self.sql)          # payload
        self.assertIn("1048576", self.sql)        # blob
        self.assertIn("209715200", self.sql)      # 200 MiB per session
        self.assertIn("interval '8 hours'", self.sql)
        self.assertIn("p_token_sha256 IS DISTINCT FROM s.token_sha256", self.sql)
        self.assertIn("read committed", self.sql)
        self.assertIn("pg_advisory_xact_lock", self.sql)
        self.assertIn("repeat('0', 64)", self.sql.replace("pg_catalog.", ""))
        self.assertIn("trace_refused", self.sql)

    def test_grants_and_assert(self):
        g = code(read(GRANTS))
        self.assertIn("GRANT USAGE ON SCHEMA agent_trace TO rs_session", g)
        self.assertIn("GRANT CONNECT ON DATABASE medcea_research TO rs_session", g)
        for f in GRANTED:
            self.assertRegex(g, r"agent_trace\.%s\(" % f)
        self.assertNotIn("verify_chain", g)
        self.assertNotRegex(g, r"ON (ALL )?TABLES?.*rs_session;\s*\n(?!REVOKE)")   # only REVOKEs name tables
        a = code(read(ASSERT))
        for s in ("rs_session is not LOGIN NOINHERIT", "rs_session lacks EXECUTE on agent_trace.", "is held by",
                  "is not SECURITY DEFINER", "does not pin search_path"):
            self.assertIn(s, a)
        for f in GRANTED:
            self.assertIn("('%s')" % f, a)

    def test_role(self):
        self.assertIn("CREATE ROLE rs_session LOGIN NOINHERIT", self.sql)
        self.assertIn("CONNECTION LIMIT 5", self.sql)
        self.assertIn("statement_timeout = '10s'", self.sql)


