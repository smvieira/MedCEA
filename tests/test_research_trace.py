def pg_bin():
    d = os.environ.get("MEDCEA_TEST_PG_BIN")
    if d:
        return d if all(os.access(os.path.join(d, b), os.X_OK) for b in ("initdb", "pg_ctl", "psql")) else None
    p = shutil.which("initdb")
    if p and shutil.which("pg_ctl") and shutil.which("psql"):
        return os.path.dirname(p)
    return None


SID = "A" * 22
SID2 = "B" * 22
H = lambda c: c * 64
SUB = "11111111-2222-3333-4444-555555555555"


def open_sql(sid, person="p1", token=None, claim=None, backend="scripted", exp="now() + interval '1 hour'"):
    return ("SELECT agent_trace.open_session('%s','k1','%s','%s','%s','%s','control_scientist','sci','scripted-v1',"
            "'%s',ARRAY['sim_run'],'{\"turns\":10}'::jsonb,'%s','abc123',%s)"
            % (sid, token or H("a"), claim or H("b"), SUB, person, H("c"), backend, exp))


@unittest.skipUnless(pg_bin(), "no initdb/pg_ctl/psql (set MEDCEA_TEST_PG_BIN)")
class RealPostgres(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.bin = pg_bin()
        cls.dir = tempfile.mkdtemp(prefix="medcea-rstr-")
        cls.sock = tempfile.mkdtemp(prefix="rstr", dir="/tmp")
        with socket.socket() as s:
            s.bind(("127.0.0.1", 0))
            cls.port = str(s.getsockname()[1])
        cmd = [os.path.join(cls.bin, "initdb"), "-D", os.path.join(cls.dir, "data"), "-U", "postgres", "-A", "trust",
               "--no-sync"]
        if os.environ.get("MEDCEA_TEST_PG_SHARE"):
            cmd += ["-L", os.environ["MEDCEA_TEST_PG_SHARE"]]
        subprocess.run(cmd, check=True, capture_output=True)
        subprocess.run([os.path.join(cls.bin, "pg_ctl"), "-D", os.path.join(cls.dir, "data"), "-w", "-l",
                        os.path.join(cls.dir, "log"), "-o", "-k %s -p %s -c listen_addresses=''" % (cls.sock, cls.port),
                        "start"], check=True, capture_output=True)
        cls.psql("postgres", read(DDL), check=True)
        cls.psql("medcea_research", read(LAKE_API), check=True)
        for _ in range(2):   # re-run safe
            cls.psql("medcea_research", read(TRACE), check=True)
            cls.psql("medcea_research", read(GRANTS), check=True)

    @classmethod
    def tearDownClass(cls):
        subprocess.run([os.path.join(cls.bin, "pg_ctl"), "-D", os.path.join(cls.dir, "data"), "-m", "immediate",
                        "stop"], capture_output=True)
        shutil.rmtree(cls.dir, ignore_errors=True)
        shutil.rmtree(cls.sock, ignore_errors=True)

    @classmethod
    def psql(cls, db, sql, user="postgres", check=False):
        r = subprocess.run([os.path.join(cls.bin, "psql"), "-X", "-h", cls.sock, "-p", cls.port, "-U", user, "-d", db,
                            "-qtA", "-v", "ON_ERROR_STOP=1", "-f", "-"], input=sql, capture_output=True, text=True,
                           env=dict(os.environ, PGTZ="UTC"))
        if check and r.returncode != 0:
            raise AssertionError(r.stderr)
        return r

    def q(self, sql, user="postgres"):
        return self.psql("medcea_research", sql, user=user, check=True).stdout.strip()

    def ev(self, port, sid, actor, event, payload="{}", token=None):
        t = "NULL" if token is None else "'%s'" % token
        out = self.q("SELECT coalesce(event_id::text, '') || '|' || coalesce(refused, '') FROM agent_trace.append_event"
                     "('%s','%s','%s','%s','%s'::jsonb,%s)" % (port, sid, actor, event, payload, t))
        eid, why = out.split("|", 1)
        return (int(eid) if eid else None), why

    def test_01_assert_is_clean(self):
        self.assertEqual(self.q(read(ASSERT)), "")

    def test_02_chain_and_allow_lists(self):
        self.q(open_sql(SID))
        self.assertTrue(self.q("SELECT ok FROM agent_trace.verify_chain()") == "t")
        e1, w = self.ev("agent", SID, "x", "tool_call", token=H("a"))
        self.assertTrue(e1 and not w)
        # R8: the agent port cannot write the person events, or a server's tool_result by actor
        for ev in ("gate_decided", "proposal_decided", "session_revoked", "claim_exchanged", "sim_finished"):
            eid, why = self.ev("agent", SID, "agent", ev, token=H("a"))
            self.assertIsNone(eid, ev)
            self.assertIn("may not write", why)
        self.assertEqual(self.q("SELECT count(*) FROM agent_trace.event WHERE event='trace_refused'"), "1")  # once
        self.assertIsNone(self.ev("agent", SID, "agent", "tool_call", token=H("f"))[0])      # not the session's token
        self.assertIsNotNone(self.ev("agent", SID, "agent", "turn_response", token=H("a"))[0])   # scripted backend
        self.assertIsNone(self.ev("server", SID, "agent", "tool_result")[0])                  # not a server actor
        self.assertIsNotNone(self.ev("server", SID, "mcp-sim", "tool_result")[0])
        self.assertIsNone(self.ev("server", SID, "mcp-sim", "turn_request")[0])               # model-gateway only
        self.assertIsNotNone(self.ev("person", SID, "x", "gate_decided")[0])
        # an oversize payload is refused
        big = '{"x":"%s"}' % ("y" * 17000)
        self.assertIn("16 KiB", self.ev("agent", SID, "agent", "tool_call", big, token=H("a"))[1])
        r = self.psql("medcea_research", "SELECT agent_trace.append_event('nope',%r,'a','tool_call','{}',NULL)" % SID)
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("unknown port", r.stderr)
        res = self.q("SELECT ok || '|' || events FROM agent_trace.verify_chain()").split("|")
        self.assertEqual(res[0], "true")
        self.assertGreaterEqual(int(res[1]), 4)

    def test_03_revocation_and_claim(self):
        self.q(open_sql(SID2, person="p2", token=H("d"), claim=H("e")))
        self.assertEqual(self.q("SELECT agent_trace.use_claim('%s','10.0.0.5')" % SID2), "t")
        self.assertEqual(self.q("SELECT agent_trace.use_claim('%s','10.0.0.6')" % SID2), "f")   # reuse revokes
        self.assertEqual(self.q("SELECT revoked FROM agent_trace.session_status('%s')" % SID2), "t")
        self.assertIsNone(self.ev("agent", SID2, "agent", "tool_call", token=H("d"))[0])
        self.assertIsNotNone(self.ev("server", SID2, "mcp-sim", "sim_finished", '{"cpu_hours":0.5}')[0])  # R9
        self.assertEqual(self.q("SELECT (spent->>'cpu_hours')::numeric FROM agent_trace.session_status('%s')" % SID2),
                         "0.5")
        self.assertEqual(self.q("SELECT agent_trace.revoke('%s','again',NULL)" % SID2), "f")

    def test_04_max_active_and_exp(self):
        self.q(open_sql("C" * 22, person="p3", token=H("1"), claim=H("2")))
        self.q(open_sql("D" * 22, person="p3", token=H("3"), claim=H("4")))
        r = self.psql("medcea_research", open_sql("E" * 22, person="p3", token=H("5"), claim=H("6")))
        self.assertIn("max_active", r.stderr)
        r = self.psql("medcea_research", open_sql("F" * 22, person="p4", token=H("7"), claim=H("8"),
                                                  exp="now() + interval '9 hours'"))
        self.assertIn("session_exp_chk", r.stderr)

    def test_05_blob_and_checkpoint(self):
        sha = self.q("SELECT agent_trace.put_blob('%s','text/plain','\\x68690a'::bytea)" % SID)
        self.assertEqual(len(sha), 64)
        self.assertEqual(self.q("SELECT agent_trace.put_blob('%s','x',repeat('a',1048577)::bytea)" % SID), "")
        self.assertEqual(self.q("SELECT agent_trace.checkpoint('%s','{\"a\":1}'::jsonb)" % SID), "1")
        self.assertEqual(self.q("SELECT agent_trace.checkpoint('%s','{\"a\":2}'::jsonb)" % SID), "2")

    def test_06_rs_session_may_only_execute(self):
        r = self.psql("medcea_research", "SELECT count(*) FROM agent_trace.event", user="rs_session")
        self.assertNotEqual(r.returncode, 0)
        r = self.psql("medcea_research", "SELECT * FROM agent_trace.verify_chain()", user="rs_session")
        self.assertNotEqual(r.returncode, 0)
        self.assertEqual(self.q("SELECT count(*) FROM agent_trace.events('%s')" % SID, user="rs_session") != "", True)

    def test_07_append_only_then_tamper(self):
        for sql in ("UPDATE agent_trace.event SET actor='z'", "DELETE FROM agent_trace.event",
                    "TRUNCATE agent_trace.event", "UPDATE agent_trace.session SET kid='z'"):
            r = self.psql("medcea_research", sql)
            self.assertNotEqual(r.returncode, 0, sql)
            self.assertIn("append-only", r.stderr)
        self.assertEqual(self.q("SELECT ok FROM agent_trace.verify_chain()"), "t")
        self.q("ALTER TABLE agent_trace.event DISABLE TRIGGER append_only_row;"
               "UPDATE agent_trace.event SET payload = '{\"x\":1}' WHERE event_id = (SELECT min(event_id) FROM agent_trace.event);"
               "ALTER TABLE agent_trace.event ENABLE ALWAYS TRIGGER append_only_row")
        res = self.q("SELECT ok || '|' || first_bad_event FROM agent_trace.verify_chain()").split("|")
        self.assertEqual(res[0], "false")
        self.assertEqual(self.q("SELECT detail FROM agent_trace.verify_chain()"), "hash does not match the row")


