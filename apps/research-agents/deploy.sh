#!/usr/bin/env bash
# apps/research-agents/deploy.sh — the research sandbox's agent machinery (research Phase 4a, stage 6b1;
# codeplan/rs4-design.md R2, R3, R4, OD11).
#
#   ./apps/research-agents/deploy.sh          ./apps/research/deploy.sh runs it after lake-api
#   ./apps/research-agents/deploy.sh --help
#
# Deploys research-session into $RESEARCH_GW_NAMESPACE (the session key and the trace writer: its two
# Secrets live there and nowhere else) and the orchestrator, mcp-sim and mcp-lake into
# $RESEARCH_AGENTS_NAMESPACE (the orchestrator's Role there lets it manage Jobs and read pods and logs
# of that namespace, nothing else). The pods run python:3.14 by digest (apps/research-model/pins.json)
# from a code bundle and hash-pinned wheels:
#   - the bundle is `git archive` of HEAD for the paths the agents need plus BUNDLE.json (commit and blob
#     SHAs), packed deterministically into ConfigMap research-code of both namespaces (server-side apply,
#     it exceeds the last-applied annotation). Refused while those paths differ from HEAD;
#   - the wheels (apps/research-agents/requirements-services.txt) are downloaded on this host into
#     $RESEARCH_WHEEL_DIR (default /var/lib/<project>/research-wheels)/{gw,agents}, one folder per zone,
#     and reach the pods as a static, read-only PersistentVolume each (Pod Security baseline refuses
#     hostPath in a pod spec, not a PV). Nothing is fetched by a pod: the zones have no internet.
# medcea-iam-lib (the route table and library) and the realm's public keys (as ConfigMap medcea-jwks:
# public keys only, so no Secret is placed in research-agents) are copied from $NAMESPACE.
#
# Prints one line and exits 0 (deploy-apps.sh and install.sh stay green) while
#   skipped: RESEARCH_ENABLED is not true
#   skipped: the applied access policy has no agent campaigns yet
#   skipped: no version of the access policy is applied yet (state ...)
#   skipped: namespace <ns> does not exist yet
#   skipped: no research database yet (./apps/research/deploy.sh)
# Running pods are left alone by a skip, and named.
#
# Then, in order: refuses unless both zones' compiled NetworkPolicies are live and equal (never an open
# pod); wheels; PVs and claims; research-runs; Secrets; the iam-lib copies; the bundle; research-session
# (rollout status); the agents' namespace (rollout status). Pods are admitted by their exec readiness
# probes (the zones admit no node source on the token ports); no secret reaches an argv.
#
# Needs config.env: RESEARCH_ENABLED, RESEARCH_NAMESPACE, RESEARCH_GW_NAMESPACE, RESEARCH_AGENTS_NAMESPACE
# (defaults ${RESEARCH_NAMESPACE}-gw / -agents), RS_SESSION_HMAC_KEY and RS_SESSION_DB_PASS (generated by
# infra/configure.sh; ./apps/research/deploy.sh sets the role's password), optional RESEARCH_WHEEL_DIR and
# RS_SIM_POOL (default 2). Idempotent. Uninstall: ./apps/research-agents/uninstall.sh.

set -euo pipefail

APP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$APP_DIR/../.." && pwd)"
SCRIPT_DIR="$REPO_ROOT"   # what infra/lib-policy-artefacts.sh calls the repository
case "$*" in
    "") ;;
    --help|-h) sed -n '2,/^set -euo pipefail/p' "$0" | sed '$d' | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "ERROR: unknown arguments: $* (usage: ./apps/research-agents/deploy.sh [--help])" >&2; exit 2 ;;
esac
source "$REPO_ROOT/infra/lib-log.sh"; medcea_log app-research-agents-deploy   # unless a parent logs
source "$REPO_ROOT/infra/lib-lock.sh"; medcea_lock   # one deploy at a time; inherited from apps/research/deploy.sh

[[ -f "$REPO_ROOT/config.env" ]] || { echo "ERROR: config.env not found at $REPO_ROOT/config.env" >&2; exit 1; }
source "$REPO_ROOT/config.env"

source "$REPO_ROOT/infra/lib-mk8s.sh"    # mk8s / $MK8S / $KUBECTL (sudo fallback)
source "$REPO_ROOT/infra/lib-render.sh"  # render FILE VAR... — manifests are in apps/research-agents/k8s/
NAMESPACE="${NAMESPACE:-medcea}"
RESEARCH_NAMESPACE="${RESEARCH_NAMESPACE:-${NAMESPACE}-research}"
source "$REPO_ROOT/infra/lib-policy-source.sh"
policy_source_init "$NAMESPACE" || exit $?   # 2: a widening git skeleton (the gate's message above)
source "$REPO_ROOT/infra/lib-policy-artefacts.sh"   # zone_namespace, _pa_zonenetpol_equal
GW_NS="$(zone_namespace research-gw)"
AG_NS="$(zone_namespace research-agents)"
export RESEARCH_NAMESPACE
RESEARCH_GW_NAMESPACE="$GW_NS"; RESEARCH_AGENTS_NAMESPACE="$AG_NS"

GREEN='\033[0;32m'; YELLOW='\033[0;33m'; RED='\033[0;31m'; NC='\033[0m'
log()  { echo -e "${GREEN}[research-agents]${NC} $*"; }
warn() { echo -e "${YELLOW}[research-agents] $*${NC}" >&2; }
die()  { echo -e "${RED}[research-agents] ERROR: $*${NC}" >&2; exit 1; }

for _v in "$GW_NS" "$AG_NS"; do
    [[ "$_v" =~ ^[a-z][a-z0-9-]{1,52}$ ]] || die "'$_v' is not a valid research namespace name (config.env)"
done
[[ "$GW_NS" != "$AG_NS" && "$GW_NS" != "$NAMESPACE" && "$AG_NS" != "$NAMESPACE" \
   && "$GW_NS" != "$RESEARCH_NAMESPACE" && "$AG_NS" != "$RESEARCH_NAMESPACE" ]] \
    || die "RESEARCH_NAMESPACE, RESEARCH_GW_NAMESPACE, RESEARCH_AGENTS_NAMESPACE and NAMESPACE must all differ (config.env)"

# A skip leaves running pods alone: it says so.
_skip() {   # _skip MESSAGE: the line, running pods named, exit 0
    log "skipped: $1"
    local _ns
    for _ns in "$GW_NS" "$AG_NS"; do
        if $KUBECTL get deployment -n "$_ns" -l app.kubernetes.io/part-of=medcea-research -o name 2>/dev/null | grep -q .; then
            warn "agent pods are still running in $_ns (left alone): ./apps/research-agents/uninstall.sh removes them"
        fi
    done
    policy_source_finish "$NAMESPACE" research-agents
    exit 0
}

# ── Skips ─────────────────────────────────────────────────────────────────────
[[ "${RESEARCH_ENABLED:-false}" == "true" ]] || _skip "RESEARCH_ENABLED is not true"

_zrc=0
_zone="$(python3 "$REPO_ROOT/apps/iam/compiler/cli.py" pod-zone research-orchestrator)" || _zrc=$?
case "$_zrc:$_zone" in
    0:research-agents) ;;
    0:*) die "the access policy puts research-orchestrator in the ${_zone:-?} zone: it lives only in research-agents (python3 apps/iam/compiler/cli.py check)" ;;
    1:*) _skip "the applied access policy has no agent campaigns yet" ;;
    *)   die "the applied access policy cannot be read (cli.py pod-zone research-orchestrator exit $_zrc): ./apps/iam/apply.sh --status says why" ;;
esac
_zrc=0
_zone="$(python3 "$REPO_ROOT/apps/iam/compiler/cli.py" pod-zone research-session)" || _zrc=$?
[[ "$_zrc:$_zone" == "0:research-gw" ]] || die "the access policy must put research-session in the research-gw zone (cli.py pod-zone research-session: '${_zone:-}', exit $_zrc)"

_PS_DIR="$(mktemp -d)"
_ST="$(policy_db_state "$NAMESPACE" "$_PS_DIR/state.json")" || _ST=""
rm -rf "$_PS_DIR"
case "$_ST" in
    version-*) ;;
    none|empty) _skip "no version of the access policy is applied yet (state $_ST): run ./apps/research-agents/deploy.sh once ./apps/iam/deploy.sh has applied version 1 (./apps/iam/apply.sh --status)" ;;
    "") die "cannot read the access policy's state from the database (policy_db_state failed)" ;;
    *)  die "the access policy's state in the database is '$_ST': ./apps/iam/apply.sh --status" ;;
esac

for _ns in "$GW_NS" "$AG_NS"; do
    $KUBECTL get namespace "$_ns" >/dev/null 2>&1 \
        || _skip "namespace $_ns does not exist yet: run ./deploy-infra.sh (or ./infra/deploy-research-gw-namespace.sh and ./infra/deploy-research-agents-namespace.sh)"
done
$KUBECTL get statefulset research-postgresql -n "$RESEARCH_NAMESPACE" >/dev/null 2>&1 \
    || _skip "no research database yet (./apps/research/deploy.sh)"

# ── Preconditions ─────────────────────────────────────────────────────────────
[[ "${RS_SESSION_HMAC_KEY:-}" =~ ^[0-9a-f]{64}$ ]] \
    || die "RS_SESSION_HMAC_KEY is empty or not 64 hex characters in config.env: run ./deploy-infra.sh (infra/configure.sh generates it)"
[[ -n "${RS_SESSION_DB_PASS:-}" && "$RS_SESSION_DB_PASS" =~ ^[A-Za-z0-9._~-]+$ ]] \
    || die "RS_SESSION_DB_PASS is empty or holds characters outside [A-Za-z0-9._~-] in config.env: run ./deploy-infra.sh, then ./apps/research/deploy.sh"
RS_SIM_POOL="${RS_SIM_POOL:-2}"
[[ "$RS_SIM_POOL" =~ ^[1-9][0-9]?$ ]] || die "RS_SIM_POOL='$RS_SIM_POOL' is not a small positive integer"

# Never an open pod: both zones' compiled policies live and equal to the compile.
for _z in research-gw research-agents; do
    _nrc=0
    _pa_zonenetpol_equal "$_z" || _nrc=$?
    case "$_nrc" in
        0) ;;
        1) die "the $_z zone's NetworkPolicies in $(zone_namespace "$_z") are not the compiled ones: run ./infra/deploy-$_z-namespace.sh (or ./deploy-infra.sh), then this again" ;;
        *) die "cannot compare the $_z zone's NetworkPolicies with the compile (exit $_nrc)" ;;
    esac
done
$KUBECTL get networkpolicy -n "$GW_NS" -o name 2>/dev/null | grep -q . \
    || die "no NetworkPolicy in $GW_NS: the compiled default-deny must be live first (./infra/deploy-research-gw-namespace.sh)"
$KUBECTL get networkpolicy -n "$AG_NS" -o name 2>/dev/null | grep -q . \
    || die "no NetworkPolicy in $AG_NS: the compiled default-deny must be live first (./infra/deploy-research-agents-namespace.sh)"

# ── 0. The image: the step-0 pin (apps/research-model/pins.json) ──────────────
RS_IMAGE="$(python3 -c 'import json, sys; print(json.load(open(sys.argv[1]))["python_image"])' "$REPO_ROOT/apps/research-model/pins.json")"
[[ "$RS_IMAGE" =~ ^python:[0-9.]+-slim@sha256:[0-9a-f]{64}$ ]] || die "apps/research-model/pins.json has no python_image pinned by digest"

# ── 1. The wheels: one host folder per zone ───────────────────────────────────
WHEEL_ROOT="${RESEARCH_WHEEL_DIR:-/var/lib/${PROJECT_NAME:-medcea}/research-wheels}"
[[ "$WHEEL_ROOT" == /* && "$WHEEL_ROOT" =~ ^[A-Za-z0-9._/-]+$ && "$WHEEL_ROOT" != *..* ]] \
    || die "RESEARCH_WHEEL_DIR='$WHEEL_ROOT' must be an absolute path of [A-Za-z0-9._/-] without '..'"
REQS="$APP_DIR/requirements-services.txt"

_wheels_missing() {   # DIR: the requirements no *.whl of DIR has the pinned sha256 for (one name per line)
    python3 - "$REQS" "$1" <<'PY'
import glob, hashlib, re, sys
req, d = sys.argv[1], sys.argv[2]
have = set()
for f in glob.glob(d + "/*.whl"):
    h = hashlib.sha256()
    with open(f, "rb") as fh:
        for b in iter(lambda: fh.read(1 << 20), b""):
            h.update(b)
    have.add(h.hexdigest())
for line in open(req):
    line = line.strip()
    if not line or line.startswith("#"):
        continue
    m = re.match(r"^([A-Za-z0-9._-]+)==\S+\s+--hash=sha256:([0-9a-f]{64})$", line)
    if not m:
        print("unparsable:" + line)
    elif m.group(2) not in have:
        print(m.group(1))
PY
}

_make_dir() {   # DIR: mode 755, owned by this account (sudo only when the parent is not writable)
    [[ -d "$1" ]] && return 0
    local _p; _p="$(dirname "$1")"
    if mkdir -p "$1" 2>/dev/null; then chmod 755 "$1"; return 0; fi
    sudo -p "[sudo] password for %u (to create $1 for the research agents' wheels): " install -d -m 755 -o "$(id -u)" -g "$(id -g)" "$1"
}

_fetch_wheels() {   # DIR: pip download into DIR on this host (the pods have no internet)
    local _tmp _pip="${MEDCEA_RESEARCH_PIP:-}"
    _tmp="$(mktemp -d)"
    if [[ -z "$_pip" ]]; then
        python3 -m venv "$_tmp/v" || { rm -rf "$_tmp"; die "python3 -m venv failed (apt install python3-venv)"; }
        _pip="$_tmp/v/bin/pip"
    fi
    "$_pip" download -q --require-hashes --only-binary=:all: --no-deps --python-version 3.14 --implementation cp \
        --abi cp314 --abi abi3 --abi none --platform manylinux2014_x86_64 --platform manylinux_2_17_x86_64 \
        --platform manylinux_2_28_x86_64 --platform any -r "$REQS" -d "$1" \
        || { rm -rf "$_tmp"; die "pip download of the research wheels failed (this host needs internet once)"; }
    rm -rf "$_tmp"
    chmod 644 "$1"/*.whl
}

_make_dir "$WHEEL_ROOT"
for _zd in gw agents; do
    _make_dir "$WHEEL_ROOT/$_zd"
    _miss="$(_wheels_missing "$WHEEL_ROOT/$_zd")"
    if [[ -n "$_miss" ]]; then
        [[ "$_miss" != unparsable:* ]] || die "cannot parse $REQS ($_miss)"
        log "Downloading the wheels for $_zd ($(echo $_miss | tr '\n' ' '))..."
        _fetch_wheels "$WHEEL_ROOT/$_zd"
        [[ -z "$(_wheels_missing "$WHEEL_ROOT/$_zd")" ]] || die "the downloaded wheels do not match the pinned hashes in $REQS"
    fi
done

# ── 2. Volumes ────────────────────────────────────────────────────────────────
log "Wheel volumes and the runs claim..."
for _zd in gw agents; do
    if [[ "$_zd" == gw ]]; then WHEEL_NS="$GW_NS"; else WHEEL_NS="$AG_NS"; fi
    WHEEL_PV="${WHEEL_NS}-research-wheels"; WHEEL_PATH="$WHEEL_ROOT/$_zd"
    render "$APP_DIR/k8s/wheels.yaml" WHEEL_NS WHEEL_PV WHEEL_PATH | $KUBECTL apply -f - >/dev/null
done
render "$APP_DIR/k8s/runs.yaml" RESEARCH_AGENTS_NAMESPACE | $KUBECTL apply -f - >/dev/null

# ── 3. research-session's Secrets (research-gw only; values on stdin) ─────────
log "Secrets research-session-key and research-session-db in $GW_NS..."
# The key's id (what research-session reports on /healthz as kid), as an annotation: health rsagent compares
# the two and never reads the key. The key reaches python through the environment, not argv.
RS_SESSION_KID="$(RS_SESSION_HMAC_KEY="$RS_SESSION_HMAC_KEY" python3 -c 'import hashlib, os; print(hashlib.sha256(bytes.fromhex(os.environ["RS_SESSION_HMAC_KEY"])).hexdigest()[:8])')"
[[ "$RS_SESSION_KID" =~ ^[0-9a-f]{8}$ ]] || die "cannot derive the session key id"
export RS_SESSION_KID
render "$APP_DIR/k8s/session-secrets.yaml" RESEARCH_GW_NAMESPACE RS_SESSION_HMAC_KEY RS_SESSION_DB_PASS RS_SESSION_KID \
    | $KUBECTL apply -f - >/dev/null
RS_SESSION_AUTH_VERSION="$($KUBECTL get secret research-session-key research-session-db -n "$GW_NS" \
                              -o jsonpath='{range .items[*]}{.metadata.resourceVersion}{"-"}{end}')"
[[ -n "$RS_SESSION_AUTH_VERSION" ]] || die "cannot read Secrets research-session-key and research-session-db back"

# ── 4. The route table and the realm's public keys, copied from the platform namespace ──
_copy_iam() {   # TARGET_NS
    $KUBECTL get configmap medcea-iam-lib -n "$NAMESPACE" -o json | python3 -c '
import json, sys
src = json.load(sys.stdin)
out = {"apiVersion": "v1", "kind": "ConfigMap", "metadata": {"name": "medcea-iam-lib", "namespace": sys.argv[1],
       "labels": {"app.kubernetes.io/part-of": "medcea-research"}}, "data": src.get("data") or {}}
if src.get("binaryData"):
    out["binaryData"] = src["binaryData"]
print(json.dumps(out))' "$1" | $KUBECTL apply -f - >/dev/null
    $KUBECTL get secret medcea-jwks -n "$NAMESPACE" -o json | python3 -c '
import base64, json, sys
src = json.load(sys.stdin)
data = {k: base64.b64decode(v).decode("utf-8") for k, v in (src.get("data") or {}).items()}
print(json.dumps({"apiVersion": "v1", "kind": "ConfigMap", "metadata": {"name": "medcea-jwks", "namespace": sys.argv[1],
      "labels": {"app.kubernetes.io/part-of": "medcea-research"}}, "data": data}))' "$1" | $KUBECTL apply -f - >/dev/null
}
log "medcea-iam-lib and medcea-jwks (public keys) into $GW_NS and $AG_NS..."
_copy_iam "$GW_NS"
_copy_iam "$AG_NS"

# ── 5. The code bundle ────────────────────────────────────────────────────────
_PATHS=(schd/cea research apps/database/recipe_types.yaml edge/templates/esp32-control.json apps/research/db/lake_api.sql apps/research-agents)
RS_CODE_COMMIT="$(git -C "$REPO_ROOT" rev-parse HEAD)"
[[ "$RS_CODE_COMMIT" =~ ^[0-9a-f]{40}$ ]] || die "cannot read the git commit of $REPO_ROOT (the code bundle is built from a commit)"
if [[ -n "$(git -C "$REPO_ROOT" status --porcelain -- "${_PATHS[@]}")" ]]; then
    die "the paths of the code bundle differ from HEAD (git status -- ${_PATHS[*]}): commit them first; the agents run a commit, never a working tree"
fi
_BD="$(mktemp -d)"
trap 'rm -rf "$_BD"' EXIT
mkdir "$_BD/stage"
git -C "$REPO_ROOT" archive "$RS_CODE_COMMIT" "${_PATHS[@]}" | tar -x -C "$_BD/stage"
git -C "$REPO_ROOT" ls-tree -r "$RS_CODE_COMMIT" -- "${_PATHS[@]}" | python3 -c '
import json, sys
files = {}
for line in sys.stdin:
    meta, path = line.rstrip("\n").split("\t", 1)
    files[path] = meta.split()[2]
print(json.dumps({"commit": sys.argv[1], "dirty": False, "files": files}, sort_keys=True, indent=1))' "$RS_CODE_COMMIT" > "$_BD/stage/BUNDLE.json"
# the top-level names, never ".": a "./" member makes a non-root tar chmod the emptyDir it unpacks into
mapfile -t _top < <(cd "$_BD/stage" && LC_ALL=C ls -A)
tar --sort=name --mtime=@0 --owner=0 --group=0 --numeric-owner -cf - -C "$_BD/stage" "${_top[@]}" | gzip -n > "$_BD/code.tgz"
RS_BUNDLE_SHA256="$(sha256sum "$_BD/code.tgz" | cut -d' ' -f1)"
[[ "$(stat -c %s "$_BD/code.tgz")" -le 900000 ]] || die "the code bundle is over 900000 bytes: a ConfigMap holds 1 MiB"
for _ns in "$GW_NS" "$AG_NS"; do
    python3 -c '
import base64, json, sys
print(json.dumps({"apiVersion": "v1", "kind": "ConfigMap", "metadata": {"name": "research-code", "namespace": sys.argv[2],
      "labels": {"app.kubernetes.io/part-of": "medcea-research"},
      "annotations": {"medcea/code-commit": sys.argv[3], "medcea/code-sha256": sys.argv[4]}},
      "binaryData": {"code.tgz": base64.b64encode(open(sys.argv[1], "rb").read()).decode()}}))' \
        "$_BD/code.tgz" "$_ns" "$RS_CODE_COMMIT" "$RS_BUNDLE_SHA256" \
        | $KUBECTL apply --server-side --force-conflicts --field-manager=medcea-research-agents -f - >/dev/null
done
log "Code bundle of commit ${RS_CODE_COMMIT:0:12} (sha256 ${RS_BUNDLE_SHA256:0:12}) in $GW_NS and $AG_NS."

# ── 6. The pods ───────────────────────────────────────────────────────────────
log "research-session in $GW_NS..."
render "$APP_DIR/k8s/research-session.yaml" NAMESPACE KEYCLOAK_REALM RESEARCH_GW_NAMESPACE RESEARCH_NAMESPACE RS_IMAGE RS_CODE_COMMIT \
    RS_BUNDLE_SHA256 RS_SESSION_AUTH_VERSION | $KUBECTL apply -f -
$KUBECTL rollout status deployment/research-session -n "$GW_NS" --timeout=5m \
    || die "research-session did not become ready: microk8s kubectl -n $GW_NS logs deployment/research-session"

log "research-orchestrator, mcp-sim and mcp-lake in $AG_NS..."
render "$APP_DIR/k8s/agents.yaml" RESEARCH_AGENTS_NAMESPACE RESEARCH_GW_NAMESPACE RESEARCH_NAMESPACE RS_IMAGE \
    RS_CODE_COMMIT RS_BUNDLE_SHA256 RS_SIM_POOL | $KUBECTL apply -f -
for _d in research-orchestrator mcp-sim mcp-lake; do
    $KUBECTL rollout status "deployment/$_d" -n "$AG_NS" --timeout=5m \
        || die "$_d did not become ready: microk8s kubectl -n $AG_NS logs deployment/$_d"
done

log "Done: research-session ($GW_NS), research-orchestrator, mcp-sim and mcp-lake ($AG_NS) run commit ${RS_CODE_COMMIT:0:12}. The agent, simulation and replay Jobs come with the next stage."
policy_source_finish "$NAMESPACE" research-agents
