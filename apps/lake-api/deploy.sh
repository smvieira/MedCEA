#!/usr/bin/env bash
# apps/lake-api/deploy.sh — the research sandbox's snapshot reader (research sandbox
# Phase 2b; codeplan/research-sandbox-plan.md "Phase 2b", owner decisions O2-O4 of
# 19 Nov 2026).
#
#   ./apps/lake-api/deploy.sh          ./apps/research/deploy.sh runs it as its last step
#   ./apps/lake-api/deploy.sh --help
#
# lake-api is PostgREST over schema lake_api of the research database (medcea_research,
# apps/research/db/lake_api.sql): read functions over the person-free snapshots, no
# identity (O2: it is network-gated; the research zone's NetworkPolicy rs-lake-api admits
# the notebooks and the node only). Notebooks read it through medcea_data.py
# (MEDCEA_LAKE=http://lake-api.<research namespace>.svc.cluster.local:3000).
#
# Prints one line and exits 0 (so deploy-apps.sh --all and install.sh stay green) while
#   skipped: RESEARCH_ENABLED is not true
#   skipped: the applied access policy has no lake-api pod yet
#   skipped: no version of the access policy is applied yet (state …)
#   skipped: namespace <ns> does not exist yet
#   skipped: no research database yet (./apps/research/deploy.sh)
# A lake-api already running is left alone by a skip, and named.
#
# Deploys, in order, into $RESEARCH_NAMESPACE:
#   0. refuses unless the research zone's compiled NetworkPolicy rs-lake-api is live and
#      every compiled zone policy equals the live one (never an open pod)
#   1. Secret lake-api-auth (key password = RS_LAKE_API_DB_PASS, on stdin)
#   2. Deployment and Service lake-api (k8s/lake-api.yaml), then rollout status
#   3. GET http://<pod IP>:3000/ from this host answers 200
#
# Needs config.env: RESEARCH_ENABLED, RESEARCH_NAMESPACE (default ${NAMESPACE}-research),
# RS_LAKE_API_DB_PASS (generated by infra/configure.sh; ./apps/research/deploy.sh sets
# the role's password from it). No password reaches an argv. Idempotent: safe to re-run.
# Uninstall: ./apps/lake-api/uninstall.sh (the research database is never touched).

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
case "$*" in
    "") ;;
    --help|-h) sed -n '2,/^set -euo pipefail/p' "$0" | sed '$d' | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "ERROR: unknown arguments: $* (usage: ./apps/lake-api/deploy.sh [--help])" >&2; exit 2 ;;
esac
source "$REPO_ROOT/infra/lib-log.sh"; medcea_log app-lake-api-deploy   # logs/app-lake-api-deploy-<ts>.log, unless a parent logs
source "$REPO_ROOT/infra/lib-lock.sh"; medcea_lock   # one deploy at a time; inherited from apps/research/deploy.sh

if [[ ! -f "$REPO_ROOT/config.env" ]]; then
    echo "ERROR: config.env not found at $REPO_ROOT/config.env" >&2
    exit 1
fi
source "$REPO_ROOT/config.env"

source "$REPO_ROOT/infra/lib-mk8s.sh"   # mk8s / $MK8S / $KUBECTL (sudo fallback)
source "$REPO_ROOT/infra/lib-render.sh"  # render FILE VAR... — manifests are in k8s/
NAMESPACE="${NAMESPACE:-medcea}"
RESEARCH_NAMESPACE="${RESEARCH_NAMESPACE:-${NAMESPACE}-research}"
source "$REPO_ROOT/infra/lib-policy-source.sh"   # where every policy read comes from (IAM Phase 4)
policy_source_init "$NAMESPACE" || exit $?   # 2: a widening git skeleton (the gate's message above)

GREEN='\033[0;32m'; YELLOW='\033[0;33m'; RED='\033[0;31m'; NC='\033[0m'
log()  { echo -e "${GREEN}[lake-api]${NC} $*"; }
warn() { echo -e "${YELLOW}[lake-api] $*${NC}" >&2; }
die()  { echo -e "${RED}[lake-api] ERROR: $*${NC}" >&2; exit 1; }

[[ "$RESEARCH_NAMESPACE" =~ ^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$ ]] \
    || die "RESEARCH_NAMESPACE='$RESEARCH_NAMESPACE' is not a Kubernetes namespace name (config.env)"

# A skip leaves a running lake-api alone: it says so.
_skip() {   # _skip MESSAGE: the line, a running lake-api named, exit 0
    log "skipped: $1"
    if $KUBECTL get deployment lake-api -n "$RESEARCH_NAMESPACE" >/dev/null 2>&1; then
        warn "lake-api is still running in $RESEARCH_NAMESPACE (left alone): ./apps/lake-api/uninstall.sh removes it"
    fi
    policy_source_finish "$NAMESPACE" lake-api
    exit 0
}

# ── Skips ─────────────────────────────────────────────────────────────────────
[[ "${RESEARCH_ENABLED:-false}" == "true" ]] || _skip "RESEARCH_ENABLED is not true"

# Where the access policy puts lake-api: only ever in the research zone.
_zrc=0
_zone="$(python3 "$REPO_ROOT/apps/iam/compiler/cli.py" pod-zone lake-api)" || _zrc=$?
case "$_zrc:$_zone" in
    0:research) ;;
    0:*) die "the access policy puts lake-api in the ${_zone:-?} zone: it lives only in the research zone (python3 apps/iam/compiler/cli.py check)" ;;
    1:*) _skip "the applied access policy has no lake-api pod yet" ;;
    *)   die "the applied access policy cannot be read (cli.py pod-zone lake-api exit $_zrc): ./apps/iam/apply.sh --status says why" ;;
esac

# Only from an applied version: before one, the compile above read the factory file.
_PS_DIR="$(mktemp -d)"
_ST="$(policy_db_state "$NAMESPACE" "$_PS_DIR/state.json")" || _ST=""
rm -rf "$_PS_DIR"
case "$_ST" in
    version-*) ;;
    none|empty) _skip "no version of the access policy is applied yet (state $_ST): run ./apps/lake-api/deploy.sh once ./apps/iam/deploy.sh has applied version 1 (./apps/iam/apply.sh --status)" ;;
    "") die "cannot read the access policy's state from the database (policy_db_state failed)" ;;
    *)  die "the access policy's state in the database is '$_ST': ./apps/iam/apply.sh --status" ;;
esac

$KUBECTL get namespace "$RESEARCH_NAMESPACE" >/dev/null 2>&1 \
    || _skip "namespace $RESEARCH_NAMESPACE does not exist yet: run ./deploy-infra.sh"
$KUBECTL get statefulset research-postgresql -n "$RESEARCH_NAMESPACE" >/dev/null 2>&1 \
    || _skip "no research database yet (./apps/research/deploy.sh)"

# ── Preconditions ─────────────────────────────────────────────────────────────
[[ -n "${RS_LAKE_API_DB_PASS:-}" ]] \
    || die "RS_LAKE_API_DB_PASS is empty in config.env: run ./deploy-infra.sh (infra/configure.sh generates it), then ./apps/research/deploy.sh"
[[ "$RS_LAKE_API_DB_PASS" =~ ^[A-Za-z0-9._~-]+$ ]] || die "RS_LAKE_API_DB_PASS holds characters outside [A-Za-z0-9._~-]"

# Never an open pod: the zone's compiled policy for lake-api must be live, and every
# compiled zone policy equal to the live one (infra/deploy-research-namespace.sh, which
# ./deploy-infra.sh and the policy rollout run, applies them).
$KUBECTL get networkpolicy rs-lake-api -n "$RESEARCH_NAMESPACE" -l medcea/rs-netpol=true -o name >/dev/null 2>&1 \
    || die "the research zone's NetworkPolicy rs-lake-api is not in $RESEARCH_NAMESPACE: run ./infra/deploy-research-namespace.sh (or ./deploy-infra.sh), then this again"
_nrc=0
( SCRIPT_DIR="$REPO_ROOT"; source "$REPO_ROOT/infra/lib-policy-artefacts.sh"; _pa_rsnetpol_equal ) || _nrc=$?
case "$_nrc" in
    0) ;;
    1) die "the research zone's NetworkPolicies in $RESEARCH_NAMESPACE are not the compiled ones: run ./infra/deploy-research-namespace.sh (or ./deploy-infra.sh), then this again" ;;
    *) die "cannot compare the research zone's NetworkPolicies with the compile (exit $_nrc)" ;;
esac

# ── 1. The login ──────────────────────────────────────────────────────────────
log "Secret lake-api-auth in $RESEARCH_NAMESPACE..."
render "$SCRIPT_DIR/k8s/auth-secret.yaml" RESEARCH_NAMESPACE RS_LAKE_API_DB_PASS \
    | $KUBECTL apply -f - >/dev/null
LAKE_AUTH_VERSION="$($KUBECTL get secret lake-api-auth -n "$RESEARCH_NAMESPACE" -o jsonpath='{.metadata.resourceVersion}')"
[[ -n "$LAKE_AUTH_VERSION" ]] || die "cannot read Secret lake-api-auth back"
LAKE_SCHEMA_SHA256="$(sha256sum "$REPO_ROOT/apps/research/db/lake_api.sql" | cut -d' ' -f1)"

# ── 2. The reader ─────────────────────────────────────────────────────────────
log "Deployment and Service lake-api in $RESEARCH_NAMESPACE..."
render "$SCRIPT_DIR/k8s/lake-api.yaml" RESEARCH_NAMESPACE LAKE_AUTH_VERSION LAKE_SCHEMA_SHA256 \
    | $KUBECTL apply -f -
$KUBECTL rollout status deployment/lake-api -n "$RESEARCH_NAMESPACE" --timeout=5m \
    || die "lake-api did not become ready: microk8s kubectl -n $RESEARCH_NAMESPACE logs deployment/lake-api"

# ── 3. It answers (from the host: the zone admits the node) ───────────────────
_ip="$($KUBECTL get pod -n "$RESEARCH_NAMESPACE" -l app=lake-api --field-selector=status.phase=Running \
          -o jsonpath='{.items[0].status.podIP}' 2>/dev/null || true)"
[[ "$_ip" =~ ^[0-9a-fA-F.:]+$ ]] || die "cannot read lake-api's pod address"
_code="$(curl -s -m 10 -o /dev/null -w '%{http_code}' "http://$_ip:3000/" || true)"
[[ "$_code" == 200 ]] || die "lake-api at $_ip:3000 answered '${_code:-nothing}', not 200: microk8s kubectl -n $RESEARCH_NAMESPACE logs deployment/lake-api"

log "Done: lake-api.$RESEARCH_NAMESPACE:3000 reads the snapshots of medcea_research as rs_lake_reader (lake_api functions only)."
policy_source_finish "$NAMESPACE" lake-api
