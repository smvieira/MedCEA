#!/usr/bin/env bash
# apps/research/deploy.sh — the research sandbox's own database (research sandbox
# Phase 2a; plan codeplan/research-sandbox-plan.md, "Phase 2a", item 4).
#
#   ./apps/research/deploy.sh          deploy-apps.sh --all runs it
#   ./apps/research/deploy.sh --help
#
# Opt-in, and only inside the research zone. It prints one line and exits 0 (so
# deploy-apps.sh --all and install.sh stay green) while
#   skipped: RESEARCH_ENABLED is not true
#   skipped: the applied access policy has no research zone yet
#   skipped: no version of the access policy is applied yet (state …): …
#   skipped: namespace <ns> does not exist yet: run ./deploy-infra.sh
# A research-postgresql already installed is left running by a skip (its data is the
# lake); ./apps/research/uninstall.sh removes it.
#
# Deploys, in order, into $RESEARCH_NAMESPACE (created by infra/deploy-research-namespace.sh,
# which ./deploy-infra.sh runs):
#   1. Secret research-postgresql-auth (the superuser's password, RESEARCH_DB_PASS, on stdin)
#   2. Helm release research-postgresql (bitnamicharts/postgresql 18.4.0, k8s/values.yaml
#      rendered into a mode-600 mktemp file; fullnameOverride, auth.existingSecret, the
#      chart's NetworkPolicies off (primary/readReplicas.networkPolicy.enabled), explicit resources, priorityClassName
#      medcea-research-low, persistence RESEARCH_DB_STORAGE), --wait; then every
#      NetworkPolicy in the namespace must carry medcea/rs-netpol=true (the zone's
#      compiled ones), or the deploy stops naming the others
#   3. db/medcea_research_ddl.sql (database medcea_research, roles rs_owner,
#      rs_export_writer, rs_backup, schemas lake, vault, sim, agent_trace, registry, the
#      append-only lake, lake.close_snapshot, vault.reserve) as postgres in
#      research-postgresql-0, SQL on stdin
#   4. db/lake_api.sql (Phase 2b: roles rs_lake_reader and rs_lake_api, schema lake_api,
#      the snapshot reader's read functions, lake.snapshot_digest_check), as postgres,
#      connected to medcea_research
#   5. the passwords of rs_export_writer (RS_EXPORT_WRITER_DB_PASS), rs_backup
#      (RS_BACKUP_DB_PASS) and rs_lake_api (RS_LAKE_API_DB_PASS), as SCRAM verifiers on
#      stdin in a log_statement=none session
#   6. db/grants.sql (written by hand: the research database is outside the access policy)
#   7. Secrets research-export-writer and research-backup in $NAMESPACE (the exporter's
#      and the backup's logins; never labelled medcea/db-role)
#   8. db/assert_grants.sql, read-only: rs_export_writer holds exactly INSERT on
#      lake.stage_* and EXECUTE on lake.close_snapshot and lake.latest_cut, rs_backup
#      pg_read_all_data, rs_lake_reader only the lake_api functions, rs_lake_api only
#      CONNECT and that membership, PUBLIC nothing. Any line it prints fails the deploy.
#   9. last, ./apps/lake-api/deploy.sh (the snapshot reader; it skips until the applied
#      access policy has a lake-api pod): deploy-apps.sh installs alphabetically, so
#      lake-api, before research, would otherwise always skip on a fresh install. Its
#      exit code is this deploy's.
#
# Needs config.env: RESEARCH_ENABLED, RESEARCH_NAMESPACE (default ${NAMESPACE}-research),
# RESEARCH_DB_STORAGE (default 10Gi), RESEARCH_DB_PASS, RS_EXPORT_WRITER_DB_PASS,
# RS_BACKUP_DB_PASS, RS_LAKE_API_DB_PASS, RS_SESSION_DB_PASS (generated by infra/configure.sh). No password
# reaches an argv.
# Idempotent: safe to re-run.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
case "$*" in
    "") ;;
    --help|-h) sed -n '2,/^set -euo pipefail/p' "$0" | sed '$d' | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "ERROR: unknown arguments: $* (usage: ./apps/research/deploy.sh [--help])" >&2; exit 2 ;;
esac
source "$REPO_ROOT/infra/lib-log.sh"; medcea_log app-research-deploy   # logs/app-research-deploy-<ts>.log, unless a parent logs
source "$REPO_ROOT/infra/lib-lock.sh"; medcea_lock   # one deploy at a time; inherited from deploy-apps.sh

if [[ ! -f "$REPO_ROOT/config.env" ]]; then
    echo "ERROR: config.env not found at $REPO_ROOT/config.env" >&2
    exit 1
fi
source "$REPO_ROOT/config.env"

source "$REPO_ROOT/infra/lib-mk8s.sh"   # mk8s / $MK8S / $KUBECTL (sudo fallback)
source "$REPO_ROOT/infra/lib-render.sh"  # render FILE VAR... — manifests are in k8s/
NAMESPACE="${NAMESPACE:-medcea}"
RESEARCH_NAMESPACE="${RESEARCH_NAMESPACE:-${NAMESPACE}-research}"
RESEARCH_DB_STORAGE="${RESEARCH_DB_STORAGE:-10Gi}"
RS_RELEASE=research-postgresql
RS_POD=research-postgresql-0
RS_DB=medcea_research

GREEN='\033[0;32m'; YELLOW='\033[0;33m'; RED='\033[0;31m'; NC='\033[0m'
log()  { echo -e "${GREEN}[research]${NC} $*"; }
warn() { echo -e "${YELLOW}[research] $*${NC}" >&2; }
die()  { echo -e "${RED}[research] ERROR: $*${NC}" >&2; exit 1; }

# A skip leaves a running research database alone (it holds the lake): it says so.
_installed_note() {
    if $KUBECTL get statefulset "$RS_RELEASE" -n "$RESEARCH_NAMESPACE" >/dev/null 2>&1; then
        warn "$RS_RELEASE is still installed in $RESEARCH_NAMESPACE and keeps its data: ./apps/research/uninstall.sh removes it (the volume stays unless --purge-data)."
    fi
}

# ── Skips ─────────────────────────────────────────────────────────────────────
if [[ "${RESEARCH_ENABLED:-false}" != "true" ]]; then
    log "skipped: RESEARCH_ENABLED is not true"
    _installed_note
    exit 0
fi

source "$REPO_ROOT/infra/lib-policy-source.sh"   # where every policy read comes from (IAM Phase 4)
policy_source_init "$NAMESPACE" || exit $?   # 2: a widening git skeleton (the gate's message above)

_zrc=0
python3 "$REPO_ROOT/apps/iam/compiler/cli.py" has-zone research >/dev/null || _zrc=$?
case "$_zrc" in
    0) ;;
    1)
        log "skipped: the applied access policy has no research zone yet"
        _installed_note
        policy_source_finish "$NAMESPACE" research
        exit 0 ;;
    *) die "the applied access policy cannot be read (cli.py has-zone research exit $_zrc): ./apps/iam/apply.sh --status says why" ;;
esac

# Only from an applied version: before one, the compile above read the factory file.
_PS_DIR="$(mktemp -d)"
_ST="$(policy_db_state "$NAMESPACE" "$_PS_DIR/state.json")" || _ST=""
rm -rf "$_PS_DIR"
case "$_ST" in
    version-*) ;;
    none|empty)
        log "skipped: no version of the access policy is applied yet (state $_ST), and the research database deploys only from an applied one: run ./apps/research/deploy.sh once ./apps/iam/deploy.sh has applied version 1 (./apps/iam/apply.sh --status)"
        policy_source_finish "$NAMESPACE" research
        exit 0 ;;
    "") die "cannot read the access policy's state from the database (policy_db_state failed)" ;;
    *) die "the access policy's state in the database is '$_ST': ./apps/iam/apply.sh --status" ;;
esac

if ! $KUBECTL get namespace "$RESEARCH_NAMESPACE" >/dev/null 2>&1; then
    log "skipped: namespace $RESEARCH_NAMESPACE does not exist yet: run ./deploy-infra.sh"
    policy_source_finish "$NAMESPACE" research
    exit 0
fi

# ── Preconditions ─────────────────────────────────────────────────────────────
for _v in RESEARCH_DB_PASS RS_EXPORT_WRITER_DB_PASS RS_BACKUP_DB_PASS RS_LAKE_API_DB_PASS RS_SESSION_DB_PASS; do
    [[ -n "${!_v:-}" ]] || die "$_v is empty in config.env: run ./deploy-infra.sh (infra/configure.sh generates it)"
    [[ "${!_v}" =~ ^[A-Za-z0-9._~-]+$ ]] || die "$_v holds characters outside [A-Za-z0-9._~-]"
done
[[ "$RESEARCH_DB_STORAGE" =~ ^[1-9][0-9]*(Mi|Gi|Ti)$ ]] \
    || die "RESEARCH_DB_STORAGE='$RESEARCH_DB_STORAGE' is not a size such as 10Gi"

source "$REPO_ROOT/apps/database/lib-db-apply.sh"   # _dba_psql: psql in the pod, password read there
source "$REPO_ROOT/infra/lib-oauth2-proxy.sh"       # helm_dockerhub_login
_rs_psql() { _DBA_NS="$RESEARCH_NAMESPACE" _DBA_POD="$RS_POD" _dba_psql "$@"; }

# ── 1-2. The release ──────────────────────────────────────────────────────────
log "Secret research-postgresql-auth..."
render "$SCRIPT_DIR/k8s/auth-secret.yaml" RESEARCH_DB_PASS \
    | $KUBECTL apply -n "$RESEARCH_NAMESPACE" -f - >/dev/null

_VALUES="$(mktemp)"; chmod 600 "$_VALUES"
trap 'rm -f "$_VALUES"' EXIT
render "$SCRIPT_DIR/k8s/values.yaml" RESEARCH_DB_STORAGE > "$_VALUES"
helm_dockerhub_login
log "Helm release $RS_RELEASE (bitnamicharts/postgresql 18.4.0) in $RESEARCH_NAMESPACE..."
$MK8S helm3 upgrade --install "$RS_RELEASE" \
    oci://registry-1.docker.io/bitnamicharts/postgresql \
    --version 18.4.0 \
    --namespace "$RESEARCH_NAMESPACE" \
    -f "$_VALUES" \
    --timeout 20m \
    --wait

# Policies are additive: one NetworkPolicy that is not the zone's (the chart's own, an
# older values file's, one made by hand) admits what the zone's default-deny refuses.
# Only the compiled ones (label medcea/rs-netpol=true) may be here.
log "NetworkPolicies in $RESEARCH_NAMESPACE (only the research zone's compiled ones)..."
_np_json="$($KUBECTL get networkpolicy -n "$RESEARCH_NAMESPACE" -o json 2>/dev/null)" \
    || die "cannot list the NetworkPolicies of $RESEARCH_NAMESPACE"
_np_bad="$(printf '%s' "$_np_json" | python3 -c '
import json, sys
try:
    items = json.load(sys.stdin)["items"]
except Exception:
    print("?unreadable"); sys.exit(0)
for i in items:
    m = i.get("metadata") or {}
    if (m.get("labels") or {}).get("medcea/rs-netpol") != "true":
        print(m.get("name", "?"))
')"
if [[ "$_np_bad" == "?unreadable" ]]; then
    die "cannot read the NetworkPolicies of $RESEARCH_NAMESPACE"
elif [[ -n "$_np_bad" ]]; then
    die "NetworkPolicy $(echo $_np_bad | sed 's/ /, /g') in $RESEARCH_NAMESPACE is not labelled medcea/rs-netpol=true: it admits more than the research zone allows. Delete it (microk8s kubectl delete networkpolicy -n $RESEARCH_NAMESPACE <name>) and run ./apps/research/deploy.sh again"
fi

# ── 3-6. Database, the snapshot reader's schema, passwords, grants ─────────────
log "Database $RS_DB (roles, schemas, the lake, the vault)..."
_out="$(_rs_psql postgres -q -v ON_ERROR_STOP=1 -f - < "$SCRIPT_DIR/db/medcea_research_ddl.sql" 2>&1)" \
    || { echo "$_out" >&2; die "db/medcea_research_ddl.sql failed in $RS_POD"; }

log "The snapshot reader's schema (db/lake_api.sql)..."
_out="$(_rs_psql "$RS_DB" -q -v ON_ERROR_STOP=1 -f - < "$SCRIPT_DIR/db/lake_api.sql" 2>&1)" \
    || { echo "$_out" >&2; die "db/lake_api.sql failed in $RS_POD"; }

log "The agent trace (db/agent_trace.sql: schema agent_trace, role rs_session)..."
_out="$(_rs_psql "$RS_DB" -q -v ON_ERROR_STOP=1 -f - < "$SCRIPT_DIR/db/agent_trace.sql" 2>&1)" \
    || { echo "$_out" >&2; die "db/agent_trace.sql failed in $RS_POD"; }

log "Passwords of rs_export_writer, rs_backup, rs_lake_api and rs_session (SCRAM verifiers)..."
_scram() { printf '%s' "$1" | python3 "$REPO_ROOT/infra/pg-scram.py"; }
{
    echo "SET log_statement = 'none';"
    printf "\\\\set pw '%s'\n" "$(_scram "$RS_EXPORT_WRITER_DB_PASS")"
    echo "ALTER ROLE rs_export_writer PASSWORD :'pw';"
    printf "\\\\set pw '%s'\n" "$(_scram "$RS_BACKUP_DB_PASS")"
    echo "ALTER ROLE rs_backup PASSWORD :'pw';"
    printf "\\\\set pw '%s'\n" "$(_scram "$RS_LAKE_API_DB_PASS")"
    echo "ALTER ROLE rs_lake_api PASSWORD :'pw';"
    printf "\\\\set pw '%s'\n" "$(_scram "$RS_SESSION_DB_PASS")"
    echo "ALTER ROLE rs_session PASSWORD :'pw';"
} | _rs_psql postgres -q -v ON_ERROR_STOP=1 -f - >/dev/null \
    || die "could not set the passwords of rs_export_writer, rs_backup, rs_lake_api and rs_session"

log "Grants (db/grants.sql)..."
_out="$(_rs_psql "$RS_DB" -q -v ON_ERROR_STOP=1 -f - < "$SCRIPT_DIR/db/grants.sql" 2>&1)" \
    || { echo "$_out" >&2; die "db/grants.sql failed in $RS_POD"; }

# ── 7. The logins the platform namespace's pods use ───────────────────────────
log "Secrets research-export-writer and research-backup in $NAMESPACE..."
SECRET_NAME=research-export-writer DB_ROLE=rs_export_writer DB_PASS="$RS_EXPORT_WRITER_DB_PASS" \
    render "$SCRIPT_DIR/k8s/role-secret.yaml" SECRET_NAME DB_ROLE DB_PASS \
    | $KUBECTL apply -n "$NAMESPACE" -f - >/dev/null
SECRET_NAME=research-backup DB_ROLE=rs_backup DB_PASS="$RS_BACKUP_DB_PASS" \
    render "$SCRIPT_DIR/k8s/role-secret.yaml" SECRET_NAME DB_ROLE DB_PASS \
    | $KUBECTL apply -n "$NAMESPACE" -f - >/dev/null

# ── 8. The grants as stated ───────────────────────────────────────────────────
log "Checking the grants..."
_out="$(_rs_psql "$RS_DB" -qtA -v ON_ERROR_STOP=1 -f - < "$SCRIPT_DIR/db/assert_grants.sql" 2>&1)" \
    || { echo "$_out" >&2; die "could not check the grants of $RS_DB"; }
if [[ -n "${_out//[[:space:]]/}" ]]; then
    echo "$_out" | sed 's/^/  /' >&2
    die "the grants of $RS_DB are not the ones db/grants.sql states (above)"
fi
log "Grants as stated: rs_export_writer stages and closes snapshots only, rs_backup reads, rs_lake_api reads through lake_api only, PUBLIC holds nothing."

log "Done: $RS_RELEASE.$RESEARCH_NAMESPACE:5432, database $RS_DB. Before the first export, hold out what must stay unseen: ./apps/research/reserve.sh add …"

# ── 9. The snapshot reader, last (inherits this log and lock; its exit code is ours) ──
_lrc=0
bash "$REPO_ROOT/apps/lake-api/deploy.sh" || _lrc=$?
[[ $_lrc == 0 ]] || exit $_lrc
policy_source_finish "$NAMESPACE" research
