"""Derived device configuration.

The split matters: `device_cfg.py` is GENERATED by the onboarding wizard and
holds nothing but literals — the slot, the credentials, the pins the operator
chose. This file is shipped as-is and derives everything that follows from them.
Re-onboarding a board rewrites device_cfg.py and leaves this file alone, so the
logic below cannot drift per board the way nine hand-edited copies of one
config.py did.

Existing fleet code says `import config as cfg`, and that keeps working.
"""

import ubinascii
import machine

import device_cfg as _d

# ---- identity, straight from the wizard ------------------------------------
ROLE        = _d.ROLE                 # SENSE | CONTROL | UNREGISTERED
STATE       = getattr(_d, "STATE", "REGISTERED")
unit_code   = getattr(_d, "UNIT_CODE", "")
zone_code   = getattr(_d, "ZONE_CODE", "")
device_dns  = _d.DEVICE_DNS           # UNIT01_SENSE_ZONE01
hostname    = _d.HOSTNAME             # u01-s-z01 — what DHCP registers

# The MAC, not the slot. Two boards must never present the same client id to the
# broker: MQTT evicts the older session on a duplicate, so a copied identity
# shows up as two devices that take turns disconnecting each other.
#
# .decode() is load-bearing. hexlify returns BYTES, and this value goes into
# every published payload — ujson.dumps() will not serialise bytes, so the whole
# message raises rather than publishing. The fleet's config.py has the same line
# without the decode, and works only because its callers happened to decode at
# each use. A str here also matches medcea.device.serial_number exactly: lowercase
# hex, no separators.
device_id   = ubinascii.hexlify(machine.unique_id()).decode()

# ---- network ----------------------------------------------------------------
wifi_ssid   = _d.WIFI_SSID
wifi_pwd    = _d.WIFI_PSK

mqtt_server = _d.MQTT_HOST
mqtt_port   = _d.MQTT_PORT

# ---- topics -----------------------------------------------------------------
# <root>/<unit>/<zone>/<sense|control>. Derived rather than stored so a board
# cannot end up publishing to a topic that disagrees with its own device_dns.
_base = "%s/%s/%s" % (_d.TOPIC_ROOT, unit_code, zone_code)

if ROLE == "CONTROL":
    topic_sub = _base + "/control/#"
    topic_pub = _base + "/control_setpoint"
    client_id = "%s-control-%s" % (_base.replace("/", "-"), device_id)
else:
    topic_pub = _base + "/sense"
    topic_sub = None
    client_id = topic_pub.replace("/", "-") + "-" + device_id

# ---- loop timing ------------------------------------------------------------
last_message     = 0
# SENSE: seconds between sampling cycles. CONTROL does not sample, it reacts —
# check_msg() is non-blocking, so what matters there is how often it is called.
message_interval = getattr(_d, "MESSAGE_INTERVAL", 30)
poll_ms          = getattr(_d, "POLL_MS", 100)

# ---- what this board carries ------------------------------------------------
# SENSE: [{"driver": "scd4x", "params": {...}, "tags": [...]}, ...]
SENSORS = getattr(_d, "SENSORS", [])
# CONTROL: the generated pin map, read from actuator_config.json at boot.
ACTUATOR_CONFIG = getattr(_d, "ACTUATOR_CONFIG", "actuator_config.json")
ACTIVE_LOW      = getattr(_d, "ACTIVE_LOW", True)
